# Write a program to perform different Arithmetic Operations on numbers in Python.

a = int(input("Enter the first number: "))  # Taking input from user for first number
b = int(input("Enter the second number: "))  # Taking input from user for second number

print("Performing Arithmetic Operations on the given numbers:\n")
print(f"The sum of {a} and {b} is: {a+b}")              # Addition
print(f"The difference of {a} and {b} is: {a-b}")       # Subtraction
print(f"The product of {a} and {b} is: {a*b}")          # Multiplication
print(f"The quotient of {a} and {b} is: {a/b:0.3f}")    # Division
print(f"The remainder of {a} and {b} is: {a%b}")        # Modular division
print(f"The floor division of {a} and {b} is: {a//b}")  # Floor division



